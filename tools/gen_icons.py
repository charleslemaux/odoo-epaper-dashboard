#!/usr/bin/env python3
"""Generate embedded 32x32 activity-type icons from Font Awesome Free.

Rasterizes a fixed set of glyphs into 1-bit 32x32 cells and writes them
as Rust data reusing the font structures: dashboard-core/src/icon_data.rs.

Usage: python tools/gen_icons.py
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

CELL = 32
ICONS = [
    ("ICON_CHECK", 0xf00c),
    ("ICON_ENVELOPE", 0xf0e0),
    ("ICON_PHONE", 0xf095),
    ("ICON_USERS", 0xf0c0),
    ("ICON_INBOX", 0xf01c),
    ("ICON_CODE", 0xf121),
    ("ICON_CUBE", 0xf1b2),
    ("ICON_MICROCHIP", 0xf2db),
    ("ICON_LIGHTBULB", 0xf0eb),
    ("ICON_CALENDAR_CHECK", 0xf274),
    ("ICON_UPLOAD", 0xf093),
    ("ICON_PEN_SQUARE", 0xf044),
    ("ICON_CLOCK", 0xf017),
]


def render_icon(font, code):
    img = Image.new("L", (CELL, CELL), 0)
    draw = ImageDraw.Draw(img)
    left, top, right, bottom = font.getbbox(chr(code))
    x = (CELL - (right - left)) // 2 - left
    y = (CELL - (bottom - top)) // 2 - top
    draw.text((x, y), chr(code), fill=255, font=font)
    px = img.load()
    rows = []
    for row in range(CELL):
        bits = 0
        for col in range(CELL):
            bits = (bits << 1) | (1 if px[col, row] >= 128 else 0)
        rows.append(bits.to_bytes(CELL // 8, "big"))
    return b"".join(rows)


def rust_variant(name):
    return "".join(p.capitalize() for p in name.removeprefix("ICON_")
                   .lower().split("_"))


def write_rs(root, blobs):
    out = ["//! Generated by tools/gen_icons.py from Font Awesome Free",
           "//! (icons CC BY 4.0, font SIL OFL 1.1, see lib/fontawesome)",
           "//! - do not edit",
           "use crate::fonts::{Font, Glyph};", "",
           "#[repr(u8)]",
           "#[derive(Clone, Copy, PartialEq, Eq, Debug)]",
           "pub enum Icon {"]
    for name, _ in ICONS:
        out.append("    %s," % rust_variant(name))
    out += ["}", "", "static ICON_GLYPHS: [Glyph; %d] = [" % len(blobs)]
    for i in range(len(blobs)):
        out.append("    Glyph {")
        out.append("        offset: %d," % (i * CELL * CELL // 8))
        out.append("        width: %d," % CELL)
        out.append("        advance: %d," % CELL)
        out.append("    },")
    out.append("];")
    blob = b"".join(blobs)
    out.append("static ICON_BITMAP: [u8; %d] = [" % len(blob))
    for i in range(0, len(blob), 16):
        out.append("    " + ", ".join("0x%02x" % b
                                      for b in blob[i:i + 16]) + ",")
    out += ["];", "",
            "pub static ICONS_32: Font = Font {",
            "    height: %d," % CELL,
            "    glyphs: &ICON_GLYPHS,",
            "    bitmap: &ICON_BITMAP,",
            "};"]
    path = root / "dashboard-core" / "src" / "icon_data.rs"
    path.write_text("\n".join(out) + "\n", newline="\n")
    print("wrote", path)


def main():
    root = Path(__file__).resolve().parent.parent
    ttf = root / "lib" / "fontawesome" / "fa-solid-900.ttf"
    font = ImageFont.truetype(str(ttf), 28)
    blobs = [render_icon(font, code) for _, code in ICONS]
    write_rs(root, blobs)
    print("icons: %d, %d bytes" % (len(blobs), len(blobs) * CELL * 4))


if __name__ == "__main__":
    main()
